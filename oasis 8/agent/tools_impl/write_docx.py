"""Tool: produce a Word document. STATE-CHANGING - needs approval.

Used for approval notes, letters and reports. Sources are listed inside the
document, so the citation trail follows the file out of the system.
"""

import datetime

from agent.tools_impl._common import OUTPUT_DIR, output_name


def tool_write_docx(title: str, body: str, sources: list = None,
                    author: str = "", filename: str = None, **_ignored):
    """Produce a Word document. STATE-CHANGING - needs approval first."""
    from docx import Document
    from docx.shared import Pt

    doc = Document()
    doc.add_heading(title or "Approval Note", level=1)

    meta = doc.add_paragraph()
    meta.add_run(
        f"Prepared {datetime.date.today().isoformat()}"
        + (f" by {author}" if author else "")
    ).italic = True

    for para in (body or "").split("\n"):
        if para.strip():
            doc.add_paragraph(para.strip())

    if sources:
        doc.add_heading("Sources", level=2)
        for i, s in enumerate(sources, 1):
            pg = f", page {s['page']}" if s.get("page") is not None else ""
            p = doc.add_paragraph(f"[{i}] {s['document']}{pg}")
            p.runs[0].font.size = Pt(9)

    doc.add_paragraph()
    note = doc.add_paragraph(
        "Generated by the Sovereign AI Workbench from documents held on "
        "premises. Every statement above is drawn from the sources listed.")
    note.runs[0].font.size = Pt(8)

    name = output_name("note", "docx", filename)
    path = OUTPUT_DIR / name
    doc.save(path)
    return {"file": name, "path": str(path)}
